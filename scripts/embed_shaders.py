#!/usr/bin/env python3
"""Writes Sources/GemmaEmbed/Metal/EmbeddedShaders.swift from Sources/GemmaEmbed/Shaders/*.metal.

usage: scripts/embed_shaders.py
Rerun after editing a shader; ShaderSourceTests fails while the two disagree.
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHADERS = ROOT / "Sources/GemmaEmbed/Shaders"
OUT = ROOT / "Sources/GemmaEmbed/Metal/EmbeddedShaders.swift"

def literal(text):
    if '"""#' in text or "\\#" in text:
        sys.exit("shader text contains a raw-string delimiter; raise the # count in embed_shaders.py")
    return '#"""\n' + text + '\n"""#'

def main():
    entries = [f'"{p.name}": {literal(p.read_text(encoding="utf-8"))},' for p in sorted(SHADERS.glob("*.metal"))]
    OUT.write_text(
        "// Generated by scripts/embed_shaders.py from Sources/GemmaEmbed/Shaders. Do not edit.\n\n"
        "/// The shader sources compiled into the library, used when no resource bundle is found.\n"
        "enum EmbeddedShaders {\n"
        "    static let sources: [String: String] = [\n"
        + "\n".join(entries) + "\n"
        "    ]\n"
        "}\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(entries)} shaders)")

main()
